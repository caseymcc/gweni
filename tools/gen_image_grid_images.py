import io
import math
import os
import sys

from PIL import Image, ImageDraw

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'examples', 'demo', 'imageGridImages.inc')


def gradient(width, height, top, bottom):
    image = Image.new('RGB', (width, height))
    pixels = image.load()
    for y in range(height):
        t = y / max(1, height - 1)
        colour = tuple(int(a + (b - a) * t) for a, b in zip(top, bottom))
        for x in range(width):
            pixels[x, y] = colour
    return image


def sunset():
    image = gradient(320, 200, (255, 140, 60), (90, 30, 120))
    draw = ImageDraw.Draw(image)
    draw.ellipse((120, 90, 200, 170), fill=(255, 220, 90))
    draw.rectangle((0, 150, 320, 200), fill=(30, 20, 60))
    return image


def tower():
    image = gradient(180, 300, (120, 190, 255), (230, 240, 255))
    draw = ImageDraw.Draw(image)
    draw.polygon([(90, 30), (130, 290), (50, 290)], fill=(70, 70, 90))
    for y in range(60, 290, 30):
        draw.line((60, y, 120, y), fill=(200, 200, 210), width=3)
    return image


def badge():
    # RGBA with transparent corners
    image = Image.new('RGBA', (256, 256), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle((8, 8, 248, 248), radius=48, fill=(60, 180, 120, 255))
    draw.ellipse((78, 78, 178, 178), fill=(255, 255, 255, 220))
    return image


def wide():
    image = gradient(400, 120, (20, 60, 90), (40, 140, 160))
    draw = ImageDraw.Draw(image)
    for i in range(8):
        x = i * 50
        draw.polygon([(x, 120), (x + 25, 40 + (i * 37) % 50), (x + 50, 120)], fill=(240, 240, 250))
    return image


def checker():
    image = Image.new('RGB', (64, 64))
    pixels = image.load()
    for y in range(64):
        for x in range(64):
            pixels[x, y] = (230, 90, 90) if ((x // 8) + (y // 8)) % 2 else (250, 230, 200)
    return image


def rings():
    image = Image.new('RGB', (300, 225), (25, 30, 45))
    draw = ImageDraw.Draw(image)
    for r in range(110, 0, -12):
        shade = int(120 + 120 * math.sin(r / 15.0))
        draw.ellipse((150 - r, 112 - r, 150 + r, 112 + r), outline=(shade, 160, 255 - shade), width=5)
    return image


def swap():
    image = gradient(240, 160, (250, 240, 120), (240, 120, 40))
    draw = ImageDraw.Draw(image)
    draw.rectangle((40, 40, 200, 120), outline=(60, 30, 20), width=6)
    draw.line((40, 40, 200, 120), fill=(60, 30, 20), width=6)
    return image


def encode(image, fmt):
    data = io.BytesIO()
    if fmt == 'png':
        image.save(data, 'PNG', optimize=True)
    else:
        image.save(data, 'JPEG', quality=82, optimize=True)
    return data.getvalue()


IMAGES = [
    ('Sunset', 'png', sunset),
    ('Tower', 'jpg', tower),
    ('Badge', 'png', badge),
    ('Wide', 'jpg', wide),
    ('Checker', 'png', checker),
    ('Rings', 'jpg', rings),
    ('Swap', 'jpg', swap),
]


def main():
    out = ['// Generated by tools/gen_image_grid_images.py; do not edit.',
           '// ImageGridDemo\'s images, drawn there from shapes and gradients.', '']
    for name, fmt, draw in IMAGES:
        image = draw()
        data = encode(image, fmt)
        out.append('// %s: %dx%d %s, %d bytes' % (name, image.width, image.height, fmt.upper(), len(data)))
        out.append('static const unsigned char g_image%s[]={' % name)
        for i in range(0, len(data), 20):
            out.append('    ' + ','.join('0x%02x' % b for b in data[i:i + 20]) + ',')
        out.append('};')
        out.append('')
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(out))
    return 0


if __name__ == '__main__':
    sys.exit(main())
